/**
 * 生成用于「覆盖校验探测真实注册路由」的候选挂载前缀集合。
 * 说明：Express 5 的 Layer 不再暴露挂载路径，无法从运行时可靠还原前缀；
 * 此处以各分组 basePath 及常见子挂载段作为探测候选（仅用于探测，不参与比对结论）。
 * @returns 去重后的候选挂载前缀列表
 */
export function buildProbeMounts(): string[] {
  const set = new Set<string>(['/api', '/uploads']);
  MODULES.forEach((module) => {
    const segments = module.basePath.split('/').filter(Boolean);
    let acc = '';
    segments.forEach((segment) => {
      acc += `/${segment}`;
      // 累计前缀（如 /api/auth）用于探测深层挂载
      set.add(acc);
      // 单段前缀（如 /auth）用于探测子路由挂载
      set.add(`/${segment}`);
    });
  });
  return Array.from(set);
}
