/**
 * 接口文档目录数据。
 * 模块职责：以强类型常量集中描述全部对外接口（分组、路径、鉴权、权限码、
 * 参数、示例、实现约定），供渲染层（render.ts）与覆盖校验层（routeAudit.ts）复用。
 *
 * 设计约定：
 * - 本文件为「数据」模块，不含任何运行时副作用，可被任意层安全引入。
 * - 所有 `path` 均为「含 `/api` 前缀」的完整路径，便于与运行时注册路由直接比对。
 * - 示例中的响应体一律带统一外层 `{ code, message, data }`，与真实返回保持一致。
 */

/** 支持的 HTTP 方法。 */
export type HttpMethod = 'GET' | 'POST' | 'PUT' | 'DELETE';

/** 单个参数的文档描述。 */
export interface ParamDoc {
  /** 参数名 */
  name: string;
  /** 类型描述（如 string / number / boolean / number[]） */
  type: string;
  /** 是否必填 */
  required: boolean;
  /** 说明 */
  description: string;
  /** 默认值（可选，字符串形式） */
  default?: string;
}

/** 单个接口的文档描述。 */
export interface EndpointDoc {
  /** HTTP 方法 */
  method: HttpMethod;
  /** 完整路径（含 /api 前缀，路径参数以 :name 表示） */
  path: string;
  /** 一句话摘要 */
  summary: string;
  /** 补充说明（可选） */
  description?: string;
  /** 是否需要登录（Authorization: Bearer <token>） */
  auth: boolean;
  /** 所需权限码（可选；留空表示登录即可访问） */
  permission?: string;
  /** 请求体类型 */
  contentType: string;
  /** 路径参数 */
  pathParams?: ParamDoc[];
  /** 查询参数 */
  queryParams?: ParamDoc[];
  /** 请求体参数 */
  bodyParams?: ParamDoc[];
  /** 请求示例（如 curl 片段） */
  requestExample?: string;
  /** 响应示例（真实结构的 JSON 字符串） */
  responseExample?: string;
  /** 实现约定 / 注意事项（可选） */
  notes?: string;
}

/** 接口分组（按业务模块）。 */
export interface ModuleDoc {
  /** 分组唯一标识 */
  key: string;
  /** 分组名称 */
  name: string;
  /** 分组挂载前缀（用于覆盖校验探测真实注册路由） */
  basePath: string;
  /** 分组说明（可选） */
  description?: string;
  /** 分组内接口列表 */
  endpoints: EndpointDoc[];
}

/** 错误码表项。 */
export interface ErrorCodeDoc {
  /** 业务错误码（与 HTTP 状态码一致） */
  code: number;
  /** 默认提示文案 */
  message: string;
  /** 触发场景说明 */
  description: string;
}

/** 通用说明。 */
export interface GeneralDoc {
  /** 文档标题 */
  title: string;
  /** 服务基地址 */
  baseUrl: string;
  /** 认证方式说明 */
  auth: string;
  /** 统一响应体说明 */
  responseFormat: string;
  /** 分页约定说明 */
  pagination: string;
  /** 静态资源与图片压缩说明 */
  staticAssets: string;
  /** 其它通用约定（逐条） */
  conventions: string[];
  /** 错误码表 */
  errorCodes: ErrorCodeDoc[];
}

